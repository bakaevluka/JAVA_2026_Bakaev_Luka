class OperatorsExample {

    public static void main(String[] args) {

        // ============================================================
        // 1. ОПЕРАТОР ПРИСВАИВАНИЯ =
        // ============================================================
        System.out.println("=== 1. Оператор присваивания (=) ===");

        int a = 10;           // присваивание значения переменной a
        int b = 5;            // присваивание значения переменной b
        String name = "Лука"; // присваивание строки
        System.out.println("a = " + a + ", b = " + b + ", name = " + name);

        // ============================================================
        // 2. СОСТАВНЫЕ ОПЕРАТОРЫ ПРИСВАИВАНИЯ (+=, -=, *=, /=, %=)
        // ============================================================
        System.out.println("\n=== 2. Составные операторы присваивания ===");

        int x = 10;
        x += 5;  // эквивалентно x = x + 5
        System.out.println("x += 5 -> x = " + x); // 15

        x -= 3;  // эквивалентно x = x - 3
        System.out.println("x -= 3 -> x = " + x); // 12

        x *= 2;  // эквивалентно x = x * 2
        System.out.println("x *= 2 -> x = " + x); // 24

        x /= 4;  // эквивалентно x = x / 4
        System.out.println("x /= 4 -> x = " + x); // 6

        x %= 4;  // эквивалентно x = x % 4
        System.out.println("x %= 4 -> x = " + x); // 2 (остаток от деления 6 на 4)

        // ============================================================
        // 3. ТЕРНАРНЫЙ ОПЕРАТОР ?:
        // ============================================================
        System.out.println("\n=== 3. Тернарный оператор (?:) ===");

        int age = 20;
        // если age >= 18, то status = "совершеннолетний", иначе "несовершеннолетний"
        String status = (age >= 18) ? "совершеннолетний" : "несовершеннолетний";
        System.out.println("Возраст " + age + " - " + status);

        // нахождение максимального числа
        int max = (10 > 20) ? 10 : 20;
        System.out.println("Максимальное из 10 и 20: " + max);

        // ============================================================
        // 4. ЛОГИЧЕСКИЕ ОПЕРАТОРЫ (||, &&, |, ^, &)
        // ============================================================
        System.out.println("\n=== 4. Логические операторы ===");

        boolean p = true;
        boolean q = false;

        // логическое ИЛИ (||) - короткозамкнутый: если первый true, второй не проверяется
        System.out.println("true || false = " + (p || q));  // true

        // логическое И (&&) - короткозамкнутый: если первый false, второй не проверяется
        System.out.println("true && false = " + (p && q));  // false

        // логическое ИЛИ без короткого замыкания (|) - проверяются оба операнда
        System.out.println("true | false = " + (p | q));    // true

        // исключающее ИЛИ (^) - true, если операнды разные
        System.out.println("true ^ false = " + (p ^ q));    // true
        System.out.println("true ^ true = " + (p ^ p));     // false

        // логическое И без короткого замыкания (&) - проверяются оба операнда
        System.out.println("true & false = " + (p & q));    // false

        // ============================================================
        // 5. ОПЕРАТОРЫ СРАВНЕНИЯ (==, !=, >, >=, <, <=)
        // ============================================================
        System.out.println("\n=== 5. Операторы сравнения ===");

        int num1 = 10;
        int num2 = 20;

        System.out.println("num1 == num2: " + (num1 == num2)); // false (равно)
        System.out.println("num1 != num2: " + (num1 != num2)); // true (не равно)
        System.out.println("num1 > num2:  " + (num1 > num2));  // false (больше)
        System.out.println("num1 >= num2: " + (num1 >= num2)); // false (больше или равно)
        System.out.println("num1 < num2:  " + (num1 < num2));  // true (меньше)
        System.out.println("num1 <= num2: " + (num1 <= num2)); // true (меньше или равно)

        // сравнение строк - важно: == сравнивает ссылки, а не содержимое
        String str1 = "Java";
        String str2 = "Java";
        String str3 = new String("Java");

        System.out.println("\nСравнение строк:");
        System.out.println("str1 == str2: " + (str1 == str2));       // true (один пул литералов)
        System.out.println("str1 == str3: " + (str1 == str3));       // false (разные объекты)
        System.out.println("str1.equals(str3): " + str1.equals(str3)); // true (сравнение содержимого)

        // ============================================================
        // 6. ПОБИТОВЫЕ ОПЕРАТОРЫ СДВИГА (>>, >>>, <<)
        // ============================================================
        System.out.println("\n=== 6. Побитовые операторы сдвига ===");

        int value = 16; // двоичное представление: 10000

        // сдвиг влево (<<) - умножение на 2 в степени n
        System.out.println("16 << 1 = " + (value << 1)); // 32 (100000)
        System.out.println("16 << 2 = " + (value << 2)); // 64 (1000000)

        // сдвиг вправо (>>) - деление на 2 в степени n (со знаком)
        System.out.println("16 >> 1 = " + (value >> 1)); // 8 (1000)
        System.out.println("16 >> 2 = " + (value >> 2)); // 4 (100)

        // беззнаковый сдвиг вправо (>>>) - всегда добавляет 0 слева
        int negative = -16;
        System.out.println("-16 >>> 1 = " + (negative >>> 1)); // 2147483640

        // ============================================================
        // 7. АРИФМЕТИЧЕСКИЕ ОПЕРАТОРЫ (+, -, *, /, %)
        // ============================================================
        System.out.println("\n=== 7. Арифметические операторы ===");

        int m = 15;
        int n = 4;

        System.out.println("m + n = " + (m + n)); // сложение: 19
        System.out.println("m - n = " + (m - n)); // вычитание: 11
        System.out.println("m * n = " + (m * n)); // умножение: 60
        System.out.println("m / n = " + (m / n)); // целочисленное деление: 3 (дробная часть отбрасывается)
        System.out.println("m % n = " + (m % n)); // остаток от деления: 3

        // ============================================================
        // 8. ОПЕРАТОРЫ ИНКРЕМЕНТА И ДЕКРЕМЕНТА (++, --)
        // ============================================================
        System.out.println("\n=== 8. Инкремент (++) и декремент (--) ===");

        int counter = 5;

        // постфиксная форма: сначала используется старое значение, потом увеличивается
        System.out.println("Исходное значение: " + counter);
        System.out.println("Постфиксный ++: " + (counter++)); // выводит 5, затем counter = 6
        System.out.println("После постфикса: " + counter);     // 6

        System.out.println("Постфиксный --: " + (counter--)); // выводит 6, затем counter = 5
        System.out.println("После постфикса --: " + counter);  // 5

        // префиксная форма: сначала увеличивается, потом используется новое значение
        counter = 5;
        System.out.println("\nПрефиксный ++: " + (++counter)); // counter = 6, выводит 6
        System.out.println("После префикса: " + counter);       // 6

        System.out.println("Префиксный --: " + (--counter)); // counter = 5, выводит 5
        System.out.println("После префикса --: " + counter); // 5

        // ============================================================
        // 9. ОПЕРАТОРЫ + И += С STRING (конкатенация)
        // ============================================================
        System.out.println("\n=== 9. Операторы + и += с String ===");

        String greeting = "Привет";
        // оператор + объединяет строки
        String result = greeting + ", " + "Лука";
        System.out.println("Конкатенация: " + result);

        String message = "Hello";
        message += " World!"; // эквивалентно message = message + " World!"
        System.out.println("+= со String: " + message);

        // смешанная конкатенация: числа автоматически преобразуются в строки
        System.out.println("Число + строка: " + (42 + " - ответ"));

        // ============================================================
        // 10. ОПЕРАТОРЫ НЕ (~ и !)
        // ============================================================
        System.out.println("\n=== 10. Операторы НЕ (~ и !) ===");

        // логическое НЕ (!) - инвертирует булево значение
        boolean flag = true;
        System.out.println("!true = " + (!flag));  // false
        System.out.println("!false = " + (!false)); // true

        // побитовое НЕ (~) - инвертирует все биты числа
        int bits = 5;  // 0101 в двоичной системе
        System.out.println("~5 = " + (~bits)); // -6 (все биты инвертированы)

        // ============================================================
        // 11. ГРУППИРУЮЩИЕ СКОБКИ ( ) - меняют приоритет операций
        // ============================================================
        System.out.println("\n=== 11. Группирующие скобки () ===");

        // без скобок: сначала умножение, потом сложение
        int calc1 = 2 + 3 * 4;     // 14
        // со скобками: сначала сложение в скобках, потом умножение
        int calc2 = (2 + 3) * 4;   // 20
        System.out.println("2 + 3 * 4 = " + calc1);
        System.out.println("(2 + 3) * 4 = " + calc2);
    }
}